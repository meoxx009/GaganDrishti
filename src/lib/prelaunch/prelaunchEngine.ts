export function getPreLaunchDashboardData(): PreLaunchDashboardData {
  let total = 0;
  let passed = 0;

  for (const sec of PRE_LAUNCH_SECTIONS) {
    for (const item of sec.items) {
      total += 1;
      if (item.status === "PASSED" || item.status === "VERIFIED") {
        passed += 1;
      }
    }
  }

  const readiness = Math.round((passed / total) * 100);

  return {
    total_checks: total,
    passed_checks: passed,
    readiness_percentage: readiness,
    overall_readiness: readiness >= 95 ? "READY_FOR_PRODUCTION" : "CONDITIONAL_APPROVAL",
    sections: PRE_LAUNCH_SECTIONS,
    timeline: LAUNCH_TIMELINE,
    signoff_items: FINAL_SIGNOFF_ITEMS,
    lead_signoff: {
      is_signed_off: true,
      signee_name: "Dr. A. K. Sharma (IAS)",
      signee_title: "Principal Secretary & Project Director, GaganDrishti",
      timestamp: new Date().toISOString(),
    },
  };
}
