/**
 * Finds the nearest or matching Climate Zone by Latitude & Longitude
 */
export function findClimateZoneByCoordinates(lat: number, lon: number): ClimateZoneRecord {
  // 1. Direct bounding box check
  const directMatch = CLIMATE_ZONES_DATABASE.find(
    (z) =>
      lat >= z.latitude_min &&
      lat <= z.latitude_max &&
      lon >= z.longitude_min &&
      lon <= z.longitude_max
  );

  if (directMatch) return directMatch;

  // 2. Nearest centroid distance calculation
  let closestZone = CLIMATE_ZONES_DATABASE[0];
  let minDistanceSq = Number.MAX_VALUE;

  for (const zone of CLIMATE_ZONES_DATABASE) {
    const centerLat = (zone.latitude_min + zone.latitude_max) / 2;
    const centerLon = (zone.longitude_min + zone.longitude_max) / 2;
    const distSq = Math.pow(lat - centerLat, 2) + Math.pow(lon - centerLon, 2);

    if (distSq < minDistanceSq) {
      minDistanceSq = distSq;
      closestZone = zone;
    }
  }

  return closestZone;
}

export function getClimateZoneById(zoneId: number): ClimateZoneRecord {
  return (
    CLIMATE_ZONES_DATABASE.find((z) => z.zone_id === zoneId) ||
    CLIMATE_ZONES_DATABASE[0]
  );
}

export function getAllClimateZones(): ClimateZoneRecord[] {
  return CLIMATE_ZONES_DATABASE;
}
