/**
 * Helper to query CROP_STAGES by crop identifier and stage
 */
export function queryCropStage(
  cropNameOrId: string,
  stageNameOrNumber?: string | number
): CropStageRecord {
  const normCrop = cropNameOrId.toLowerCase().trim();

  // Find all stages for this crop
  let cropRecords = CROP_STAGES_DATABASE.filter(
    (r) =>
      r.crop_id.toLowerCase() === normCrop ||
      r.crop_name.toLowerCase() === normCrop ||
      (normCrop.includes("chana") && r.crop_id === "chickpea") ||
      (normCrop.includes("dhan") && r.crop_id === "paddy") ||
      (normCrop.includes("rice") && r.crop_id === "paddy") ||
      (normCrop.includes("gehu") && r.crop_id === "wheat") ||
      (normCrop.includes("makka") && r.crop_id === "maize") ||
      (normCrop.includes("corn") && r.crop_id === "maize")
  );

  if (cropRecords.length === 0) {
    // Default fallback to Soybean
    cropRecords = CROP_STAGES_DATABASE.filter((r) => r.crop_id === "soybean");
  }

  if (stageNameOrNumber !== undefined && stageNameOrNumber !== null) {
    if (typeof stageNameOrNumber === "number") {
      const match = cropRecords.find((r) => r.stage_number === stageNameOrNumber);
      if (match) return match;
    } else {
      const normStage = stageNameOrNumber.toString().toLowerCase();
      const match = cropRecords.find(
        (r) =>
          r.stage_name.toLowerCase().includes(normStage) ||
          r.stage_name_hi.toLowerCase().includes(normStage) ||
          (normStage.includes("sow") && r.stage_number === 1) ||
          (normStage.includes("veg") && r.stage_number === 2) ||
          (normStage.includes("flower") && r.stage_number === 3) ||
          (normStage.includes("pod") && r.stage_number === 4) ||
          (normStage.includes("grain") && (r.stage_number === 4 || r.stage_number === 3)) ||
          (normStage.includes("matur") && r.stage_number === 5)
      );
      if (match) return match;
    }
  }

  // Default to vegetative stage (stage 2)
  return cropRecords[1] || cropRecords[0];
}

