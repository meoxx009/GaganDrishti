export function queryCropStagesList(cropName: string): CropStageRecord[] {
  const normCrop = cropName.toLowerCase().trim();
  let cropRecords = CROP_STAGES_DATABASE.filter(
    (r) =>
      r.crop_name.toLowerCase() === normCrop ||
      r.crop_id.toLowerCase() === normCrop ||
      normCrop.includes(r.crop_id) ||
      (normCrop.includes("chana") && r.crop_id === "chickpea") ||
      (normCrop.includes("dhan") && r.crop_id === "paddy") ||
      (normCrop.includes("rice") && r.crop_id === "paddy") ||
      (normCrop.includes("gehu") && r.crop_id === "wheat") ||
      (normCrop.includes("makka") && r.crop_id === "maize") ||
      (normCrop.includes("corn") && r.crop_id === "maize")
  );

  if (cropRecords.length === 0) {
    cropRecords = CROP_STAGES_DATABASE.filter((r) => r.crop_id === "soybean");
  }

  return [...cropRecords].sort((a, b) => a.stage_number - b.stage_number);
}
